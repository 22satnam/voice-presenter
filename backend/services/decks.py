"""Runtime PPTX parsing, with built-in JSON demos when no original PPTX exists."""
from io import BytesIO
import json
from pathlib import Path
from typing import Any
from fastapi import HTTPException
from pptx import Presentation

ROOT = Path(__file__).resolve().parent.parent
PRESETS = ROOT / 'presets'
MAX_PPTX = 8 * 1024 * 1024


def list_decks() -> list[dict[str, Any]]:
    found = []
    for path in sorted(PRESETS.glob('*.json')):
        d = json.loads(path.read_text(encoding='utf-8'))
        found.append({'id': d['id'], 'title': d['title'], 'blurb': d.get('blurb', ''), 'slides': len(d.get('slides', []))})
    for path in sorted(PRESETS.glob('*.pptx')):
        if not (PRESETS / f'{path.stem}.json').exists():
            found.append({'id': path.stem, 'title': path.stem.replace('-', ' ').title(), 'blurb': 'PPTX preset'})
    return found


def preset(deck_id: str) -> dict[str, Any]:
    if not deck_id.replace('-', '').replace('_', '').isalnum():
        raise HTTPException(status_code=404, detail='Deck not found')
    pptx_path = PRESETS / f'{deck_id}.pptx'
    json_path = PRESETS / f'{deck_id}.json'
    if pptx_path.exists():
        parsed = parse_pptx(pptx_path.read_bytes(), name=deck_id)
        parsed['id'] = deck_id
        if json_path.exists():
            meta = json.loads(json_path.read_text(encoding='utf-8'))
            parsed.update({k: meta.get(k, parsed.get(k)) for k in ('title', 'blurb', 'suggestions')})
        return parsed
    if json_path.exists():
        return json.loads(json_path.read_text(encoding='utf-8'))
    raise HTTPException(status_code=404, detail='Deck not found')


def parse_pptx(data: bytes, name: str = 'Uploaded presentation') -> dict[str, Any]:
    if len(data) > MAX_PPTX:
        raise HTTPException(status_code=413, detail='PPTX exceeds 8 MB limit')
    if not data.startswith(b'PK'):
        raise HTTPException(status_code=422, detail='Invalid PPTX upload')
    try:
        pres = Presentation(BytesIO(data))
    except Exception as exc:
        raise HTTPException(status_code=422, detail='Unreadable PPTX') from exc
    if not 1 <= len(pres.slides) <= 80:
        raise HTTPException(status_code=422, detail='PPTX must have 1 to 80 slides')
    slides = []
    for i, slide in enumerate(pres.slides):
        title = slide.shapes.title.text.strip() if slide.shapes.title and slide.shapes.title.has_text_frame else f'Slide {i+1}'
        bullets = []
        for shape in slide.shapes:
            if shape == slide.shapes.title or not shape.has_text_frame:
                continue
            for paragraph in shape.text_frame.paragraphs:
                item = paragraph.text.strip()
                if item and len(bullets) < 18:
                    bullets.append(item[:500])
        try:
            notes = slide.notes_slide.notes_text_frame.text.strip() if slide.has_notes_slide else ''
        except (AttributeError, ValueError):
            notes = ''
        notes = notes[:3000]
        slides.append({
            'title': title[:200], 'bullets': bullets, 'notes': notes,
            # no prefabricated answer/narration: both generated by model
            'narration': '', 'keywords': [],
        })
    return {
        'id': 'upload', 'title': Path(name).stem[:100],
        'blurb': f'Uploaded deck · {len(slides)} slides',
        'suggestions': ['Summarize this slide', 'Explain the key points', 'Next slide'],
        'slides': slides,
    }
